// The model's instructions, taken from the app (Novelo: mind/Brain.kt, Brain.SYSTEM) so the page asks
// exactly what the phone asks. Run after the prompt changes in the app:
//   node web/tools/prompt-from-app.mjs ../Novelo/app/src/main/java/com/villamediana/novelo/mind/Brain.kt
import fs from 'node:fs';
import path from 'node:path';

const src = fs.readFileSync(process.argv[2], 'utf8');
const m = /val SYSTEM: String = """\n([\s\S]*?)""".trim\(\)/.exec(src);
if (!m) throw new Error('Brain.SYSTEM não achado');
// A Kotlin raw string: what is written is what it is (trim() as the app does).
const text = m[1].trim();
if (/\$\{|\$[a-zA-Z]/.test(text)) throw new Error('o prompt tem um modelo ($…): trate antes de copiar');
const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/core/prompt.js');
fs.writeFileSync(out, `// Generated by web/tools/prompt-from-app.mjs from the app's mind/Brain.kt: do not edit here.\nexport const SYSTEM = ${JSON.stringify(text)};\n`);
console.log(`prompt.js: ${text.length} caracteres`);
